#!/usr/bin/env node
/**
 * Fetch the DOOM WebAssembly module and bake it into the driver bundle.
 *
 * The engine is `jacobenget/doom.wasm` — the original id Software DOOM sources
 * (via doomgeneric) compiled to a single freestanding wasm module with a tiny,
 * fully documented import surface. It has no DOM and no WASI dependency, which
 * is exactly why it can run inside Drawdy's shared driver worker. The DOOM
 * shareware WAD is embedded inside the module, so the game needs no data files.
 *
 * The download is pinned by SHA-256. The wasm is gzipped and base64-encoded
 * into a generated TS module so the shipped .drawdyx is completely self
 * contained and works offline.
 */
import { createHash } from "node:crypto";
import { gzipSync } from "node:zlib";
import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const RELEASE = {
    repo: "jacobenget/doom.wasm",
    tag: "v0.1.0",
    asset: "doom-v0.1.0.wasm",
    bytes: 4559928,
    sha256: "8edfe49a7583fd975199969302d8e9adcf8e714d0af72bf3e672f991fd810faa",
};
const URL_ = `https://github.com/${RELEASE.repo}/releases/download/${RELEASE.tag}/${RELEASE.asset}`;

const cache = join(ROOT, "assets", RELEASE.asset);
const outDir = join(ROOT, "src", "generated");
const out = join(outDir, "doom-wasm.ts");

const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

async function acquire() {
    if (existsSync(cache)) {
        const buf = readFileSync(cache);
        if (sha256(buf) === RELEASE.sha256) {
            console.log(`[doom] cache hit  ${RELEASE.asset} (${buf.length} bytes)`);
            return buf;
        }
        console.log("[doom] cached copy failed checksum, re-downloading");
    }
    console.log(`[doom] downloading ${URL_}`);
    const res = await fetch(URL_, { redirect: "follow" });
    if (!res.ok) throw new Error(`download failed: HTTP ${res.status} ${res.statusText}`);
    const buf = Buffer.from(await res.arrayBuffer());
    const got = sha256(buf);
    if (got !== RELEASE.sha256) {
        throw new Error(`checksum mismatch for ${RELEASE.asset}\n  expected ${RELEASE.sha256}\n  got      ${got}`);
    }
    mkdirSync(dirname(cache), { recursive: true });
    writeFileSync(cache, buf);
    console.log(`[doom] verified and cached (${buf.length} bytes)`);
    return buf;
}

const wasm = await acquire();
if (wasm.length !== RELEASE.bytes) throw new Error(`unexpected size ${wasm.length}`);

// Regenerate only when the inputs actually changed — keeps `vite` hot reloads snappy.
const gz = gzipSync(wasm, { level: 9 });
const b64 = gz.toString("base64");
const header = `// GENERATED by scripts/fetch-doom-wasm.mjs — do not edit.`;
const body = `${header}
// source : ${URL_}
// sha256 : ${RELEASE.sha256}
// wasm   : ${wasm.length} bytes -> gzip ${gz.length} bytes -> base64 ${b64.length} chars
// license: GPL-2.0-or-later (DOOM source release / doomgeneric)

/** gzip(doom.wasm), base64-encoded. Inflate with {@link inflateDoomWasm}. */
export const DOOM_WASM_GZ_BASE64 =
    "${b64}";

export const DOOM_WASM_SHA256 = "${RELEASE.sha256}";
export const DOOM_WASM_BYTES = ${wasm.length};
`;

if (existsSync(out) && readFileSync(out, "utf8") === body) {
    console.log(`[doom] ${out.replace(ROOT + "/", "")} already up to date`);
} else {
    mkdirSync(outDir, { recursive: true });
    writeFileSync(out, body);
    console.log(
        `[doom] wrote src/generated/doom-wasm.ts  (wasm ${wasm.length} -> gz ${gz.length} -> b64 ${b64.length}, ` +
            `${(statSync(out).size / 1048576).toFixed(2)} MiB on disk)`
    );
}
